CREATE OR REPLACE FUNCTION segment_studio_retire_unsupported_inherited_provenance()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
    UPDATE segment_studio_segment_provenance AS inherited
    SET superseded_at = CURRENT_TIMESTAMP,
        updated_at = CURRENT_TIMESTAMP
    WHERE inherited.relation = 'inherited'
      AND inherited.superseded_at IS NULL
      AND NOT EXISTS (
          WITH RECURSIVE ancestors(node_id) AS (
              SELECT edge.source_node_id
              FROM segment_studio_derivation_edges AS edge
              WHERE edge.derived_node_id = inherited.lineage_node_id
              UNION
              SELECT edge.source_node_id
              FROM segment_studio_derivation_edges AS edge
              JOIN ancestors
                ON edge.derived_node_id = ancestors.node_id
          )
          SELECT 1
          FROM ancestors
          JOIN segment_studio_segment_provenance AS origin
            ON origin.lineage_node_id = ancestors.node_id
          WHERE origin.relation = 'origin'
            AND origin.superseded_at IS NULL
            AND origin.source_id = inherited.source_id
            AND origin.activity_id IS NOT DISTINCT FROM inherited.activity_id
            AND origin.model_key IS NOT DISTINCT FROM inherited.model_key
            AND origin.model_identifier IS NOT DISTINCT FROM inherited.model_identifier
            AND origin.model_version IS NOT DISTINCT FROM inherited.model_version
      );
END
$function$
;

