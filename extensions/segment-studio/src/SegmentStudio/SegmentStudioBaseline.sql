-- Trigger functions.
CREATE OR REPLACE FUNCTION segment_studio_delete_rule_derivations()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    removed_edge_ids BIGINT[] := ARRAY[]::BIGINT[];
    deleted_node_ids UUID[] := ARRAY[]::UUID[];
    added_edge_ids BIGINT[];
    added_node_ids UUID[];
    deleted_item_ids BIGINT[];
    deleted_native_segment_ids INTEGER[];
    deleted_video_ids INTEGER[];
BEGIN
    removed_edge_ids := ARRAY(
        SELECT edge.id
        FROM segment_studio_derivation_edges AS edge
        WHERE edge.rule_id = OLD.id
    );

    LOOP
        added_node_ids := ARRAY(
            SELECT DISTINCT removed.derived_node_id
            FROM segment_studio_derivation_edges AS removed
            WHERE removed.id = ANY(removed_edge_ids)
              AND removed.derived_node_id <> ALL(deleted_node_ids)
              AND NOT EXISTS (
                  SELECT 1
                  FROM segment_studio_derivation_edges AS incoming
                  WHERE incoming.derived_node_id = removed.derived_node_id
                    AND incoming.id <> ALL(removed_edge_ids)
              )
        );
        deleted_node_ids := deleted_node_ids || added_node_ids;

        added_edge_ids := ARRAY(
            SELECT outgoing.id
            FROM segment_studio_derivation_edges AS outgoing
            WHERE outgoing.source_node_id = ANY(deleted_node_ids)
              AND outgoing.id <> ALL(removed_edge_ids)
        );
        removed_edge_ids := removed_edge_ids || added_edge_ids;

        EXIT WHEN cardinality(added_node_ids) = 0
            AND cardinality(added_edge_ids) = 0;
    END LOOP;

    deleted_item_ids := ARRAY(
        SELECT node.item_id
        FROM segment_studio_lineage_nodes AS node
        WHERE node.id = ANY(deleted_node_ids)
          AND node.item_id IS NOT NULL
    );
    deleted_native_segment_ids := ARRAY(
        SELECT item.native_segment_id
        FROM segment_studio_items AS item
        WHERE item.id = ANY(deleted_item_ids)
          AND item.native_segment_id IS NOT NULL
    );
    deleted_video_ids := ARRAY(
        SELECT DISTINCT node.last_known_video_id
        FROM segment_studio_lineage_nodes AS node
        WHERE node.id = ANY(deleted_node_ids)
    );

    DELETE FROM segment_studio_lineage_issues AS issue
    WHERE issue.edge_id = ANY(removed_edge_ids)
       OR issue.lineage_node_id = ANY(deleted_node_ids);

    DELETE FROM segment_studio_incorrect_examples AS example
    WHERE example.item_id = ANY(deleted_item_ids);

    DELETE FROM segment_studio_history_sessions AS session
    WHERE session.video_id = ANY(deleted_video_ids);

    DELETE FROM segment_studio_derivation_edges AS edge
    WHERE edge.id = ANY(removed_edge_ids);

    DELETE FROM segment_studio_segment_provenance AS assertion
    WHERE assertion.lineage_node_id = ANY(deleted_node_ids);

    DELETE FROM segment_studio_lineage_nodes AS node
    WHERE node.id = ANY(deleted_node_ids);

    DELETE FROM segments AS segment
    WHERE segment."Id" = ANY(deleted_native_segment_ids);

    DELETE FROM segment_studio_items AS item
    WHERE item.id = ANY(deleted_item_ids);

    PERFORM segment_studio_retire_unsupported_inherited_provenance();

    RETURN OLD;
END
$function$
;
