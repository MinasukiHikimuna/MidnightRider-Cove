-- Name: segment_studio_review_segments; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW segment_studio_review_segments AS
 SELECT "Id" AS segment_id,
    "HostId" AS video_id,
    "TagId" AS tag_id,
        CASE
            WHEN ((("Payload" -> 'segmentStudio'::text) ->> 'reviewState'::text) = ANY (ARRAY['approved'::text, 'rejected'::text])) THEN (("Payload" -> 'segmentStudio'::text) ->> 'reviewState'::text)
            ELSE 'unreviewed'::text
        END AS review_state
   FROM segments
  WHERE (("HostType" = 1) AND ("Kind" = 'tag'::text) AND ("TagId" IS NOT NULL));


