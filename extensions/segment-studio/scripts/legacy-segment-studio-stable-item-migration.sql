CREATE VIEW segment_studio_item_compatibility AS
SELECT
    item.id AS item_id,
    segment."Id" AS native_segment_id,
    segment."HostId" AS video_id,
    segment."TagId" AS tag_id,
    segment."StartSec" AS start_sec,
    segment."EndSec" AS end_sec,
    CASE
        WHEN segment."Payload" -> 'segmentStudio' ->> 'reviewState' IN ('approved', 'rejected')
            THEN segment."Payload" -> 'segmentStudio' ->> 'reviewState'
        ELSE 'unreviewed'
    END AS legacy_review_state
FROM segments AS segment
LEFT JOIN segment_studio_items AS item ON item.native_segment_id = segment."Id"
WHERE segment."HostType" = 1
  AND segment."Kind" = 'tag'
  AND segment."TagId" IS NOT NULL;
