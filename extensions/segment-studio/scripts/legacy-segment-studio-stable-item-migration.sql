    ADD CONSTRAINT "FK_segment_studio_segment_slots_items"
        FOREIGN KEY (item_id) REFERENCES segment_studio_items (id) ON DELETE CASCADE;

CREATE INDEX "IX_segment_studio_segment_slots_definition"
